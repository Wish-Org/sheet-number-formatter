import { describe, it, expect } from "vitest";
import { SheetNumberFormatter, enUS } from "../../src/index.js";

// Ported from .NET ExcelNumberFormat TestFraction and TestFractionAlignmentSuffix

const snf = new SheetNumberFormatter();
const f = (fmt: string, v: number) => {
  const r = snf.compile(fmt);
  if (!r.isSuccess) throw r.errors[0];
  return r.formatter.format(v, enUS);
};

// ─── ? space padding and 0 zero padding ──────────────────────────────────────

describe("??/?? — ? pads with spaces", () => {
  it("0   → \" 0/1 \"",  () => expect(f("??/??", 0)).toBe(" 0/1 "));
  it("1.5 → \" 3/2 \"",  () => expect(f("??/??", 1.5)).toBe(" 3/2 "));
  it("3.4 → \"17/5 \"",  () => expect(f("??/??", 3.4)).toBe("17/5 "));
  it("4.3 → \"43/10\"",  () => expect(f("??/??", 4.3)).toBe("43/10"));
});

describe("00/00 — 0 pads with zeros", () => {
  it("0   → \"00/01\"",  () => expect(f("00/00", 0)).toBe("00/01"));
  it("1.5 → \"03/02\"",  () => expect(f("00/00", 1.5)).toBe("03/02"));
  it("3.4 → \"17/05\"",  () => expect(f("00/00", 3.4)).toBe("17/05"));
  it("4.3 → \"43/10\"",  () => expect(f("00/00", 4.3)).toBe("43/10"));
});

